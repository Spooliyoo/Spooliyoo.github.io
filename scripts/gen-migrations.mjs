// Bundles drizzle/*.sql into a TS module so migrations can run inside the browser (no filesystem there).
// Run after `npx drizzle-kit generate`:  node scripts/gen-migrations.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const files = readdirSync("drizzle")
  .filter((f) => f.endsWith(".sql"))
  .sort();
const entries = files.map((f, i) => {
  const statements = readFileSync(`drizzle/${f}`, "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean);
  return { version: i + 1, name: f.replace(/\.sql$/, ""), statements };
});
const out = `// AUTO-GENERATED by scripts/gen-migrations.mjs — do not edit by hand.\n\nexport const MIGRATIONS: { version: number; name: string; statements: string[] }[] = ${JSON.stringify(entries, null, 2)};\n`;
writeFileSync("src/lib/db/migrations.generated.ts", out);
console.log(`Wrote ${entries.length} migration(s)`);
